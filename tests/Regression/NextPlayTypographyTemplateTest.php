<?php

namespace Tests\Regression;

use Tests\TestCase;

class NextPlayTypographyTemplateTest extends TestCase
{
    public function test_template_colors_fonts_and_sizes_are_centralized(): void
    {
        $theme = file_get_contents(resource_path('css/storefront-theme.css'));
        $css = file_get_contents(resource_path('css/storefront-typography.css'));
        $layout = file_get_contents(resource_path('views/components/layouts/storefront.blade.php'));

        foreach ([
            '--np-font-ui: "Expose", "Segoe UI", sans-serif;',
            '--np-color-primary: #051e44;',
            '--np-color-secondary: #CF5D38;',
            '--np-color-secondary-hover: #ad4023;',
            '--np-color-body: #26364b;',
            '--np-color-muted: #52637a;',
            '--np-color-border: #bac6d5;',
            '--nps-h1: 2.5rem;', '--nps-h2: 2rem;', '--nps-h3: 1.5rem;',
            '--nps-h4: 1.25rem;', '--nps-body: 1rem;', '--nps-menu: .9375rem;',
            '--nps-button-weight: 500;',
        ] as $expected) {
            $this->assertStringContainsString($expected, $theme);
        }

        foreach (['.np-home-section-title', '.np-home-section-description', '.np-home-action',
            '.np-best-gear-card__title', '.np-ordering-card__title', '.np-shop-sport-card__title',
            '.np-home-quick-help-card-title', '.faq-q', '.np-home-newsletter-input',
            '.np-utility-link', '.storefront-main-nav a', '.np-mobile-nav-link'] as $selector) {
            $this->assertStringContainsString($selector, $css);
        }

        $this->assertStringContainsString("asset('css/storefront-typography.css')", $layout);
        $this->assertStringContainsString('@vite([', $layout);
    }

    public function test_published_typography_asset_is_generated_from_central_sources(): void
    {
        $expected = '/* GENERATED by deploy/build-storefront-typography.py - do not edit. */'."\n"
            .file_get_contents(resource_path('css/storefront-theme.css'))."\n\n"
            .file_get_contents(resource_path('css/storefront-typography.css'))."\n";
        $this->assertSame($expected, file_get_contents(public_path('css/storefront-typography.css')));
    }

    public function test_product_card_keeps_its_own_type_rules_and_font_installer_is_available(): void
    {
        $css = file_get_contents(resource_path('css/storefront-typography.css'));
        $card = file_get_contents(resource_path('views/components/storefront/product-card.blade.php'));
        $this->assertStringContainsString(':not(.np-product-card *)', $css);
        $this->assertStringContainsString('np-product-card--canonical', $card);
        $this->assertStringNotContainsString('.np-product-card-title{font-size:', $css);
        $this->assertStringNotContainsString('.np-product-card-price{font-size:', $css);
        $this->assertFileExists(base_path('deploy/install-expose-fonts.sh'));
        $this->assertStringContainsString('fonts/expose/Expose-Regular.woff2', file_get_contents(resource_path('css/storefront-theme.css')));
    }
}
