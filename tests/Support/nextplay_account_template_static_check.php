<?php

// Runs without Composer dependencies: php tests/Support/nextplay_account_template_static_check.php
$root = dirname(__DIR__, 2);
$get = static function (string $path) use ($root): string {
    $value = file_get_contents($root.'/'.$path);
    if ($value === false) {
        throw new RuntimeException('Missing source: '.$path);
    }
    return $value;
};
$css = $get('resources/css/storefront-typography.css');
$theme = $get('resources/css/storefront-theme.css');
$published = $get('public/css/storefront-typography.css');
$layout = $get('resources/views/components/layouts/storefront.blade.php');
$frame = $get('resources/views/components/storefront/account/frame.blade.php');
$sidebar = $get('resources/views/components/storefront/account/sidebar.blade.php');
$assert = static function (bool $pass, string $message): void {
    if (! $pass) {
        throw new RuntimeException($message);
    }
};
foreach (['--nps-font:', '--nps-menu: .9375rem;', '--nps-control: 48px;',
    '--nps-h1: 2.5rem;', '--nps-h2: 2rem;', '--nps-h3: 1.5rem;',
    '--nps-body: 1rem;', '--nps-small: .875rem;', '--nps-caption: .8125rem;',
    '--nps-navy:', '--nps-link:', '--nps-muted:'] as $token) {
    $assert(str_contains($theme, $token), 'Missing template token '.$token);
}
foreach (['np-account-prototype-nav__link', 'np-artwork-button', 'np-rq-reference',
    'np-rq-tabs > a', 'np-rewards-sidebar__link', 'np-artwork-stat strong',
    'np-referral-fact strong', '.np-account-prototype-content :is(.font-black',
    '.np-account-prototype-content .text-xs', 'np-account-prototype-content :is(table',
    'np-account-prototype-content :is(label:not(.sr-only),legend',
    'np-account-prototype-content :is(input,textarea,select)',
    'np-account-prototype-content h1', 'np-account-prototype-content h2',
    'np-account-prototype-content h3', 'np-account-prototype-content h4'] as $selector) {
    $assert(str_contains($css, $selector), 'Missing account rule '.$selector);
}
$assert(str_contains($css, 'font: 500 var(--nps-menu)/1.4 var(--nps-font)'), 'Sidebar does not use template menu font');
$assert(str_contains($css, 'min-height: 44px;'), 'Sidebar/tabs do not use 44px menu geometry');
$assert(str_contains($css, 'font:500 var(--nps-button-size)/1.4 var(--nps-font)'), 'Account actions do not use template button typography');
$assert(str_contains($css, 'font:500 var(--nps-small)/1.5 var(--nps-font)'), 'Account form labels do not use 14px/500');
$assert(str_contains($css, 'var(--nps-inverse) !important'), 'Selected sidebar link must remain legible on navy');
$assert(str_contains($sidebar, 'aria-current="page"'), 'Selected sidebar navigation missing semantic state');
$assert(str_contains($frame, '<x-storefront.account.sidebar'), 'Shared frame missing sidebar');
$assert(str_contains($layout, '?v=20261031accountcompact4'), 'Updated account CSS cache-bust query missing');
$expected = '/* GENERATED by deploy/build-storefront-typography.py - do not edit. */' . "\n" .
    $theme . "\n\n" . $css . "\n";
$assert($published === $expected, 'Published typography stylesheet does not match centralized sources');
$accountFiles = glob($root.'/resources/views/storefront/account/*.blade.php');
$iter = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root.'/resources/views/storefront/account'));
$count = 0;
foreach ($iter as $file) {
    if (! $file->isFile() || ! str_ends_with($file->getFilename(), '.blade.php')) continue;
    if (str_contains($file->getPathname(), '/partials/')) continue;
    if ($file->getBasename() === 'section.blade.php') continue; // Unavailable page has direct scoped root.
    $body = file_get_contents($file->getPathname());
    $assert(preg_match('/<x-storefront\.account\.(?:page|shell|frame|orders\.page|rewards\.page)\b/', $body) === 1,
        'Unwrapped account page: '.$file->getPathname());
    $count++;
}
$assert($count >= 25, 'Account page coverage unexpectedly low');
$assert(str_contains($get('resources/views/storefront/account/section.blade.php'), 'np-account-unavailable'), 'Fallback page not scoped');
$assert(! str_contains($css, '.np-product-card {'), 'Account typography must not target product card');
$assert(! str_contains($css, '.np-filter-shell {'), 'Account typography must not target catalog filters');
echo 'PASS: account typography template roles, '.$count.' account views, published CSS, protected selectors.' . PHP_EOL;
