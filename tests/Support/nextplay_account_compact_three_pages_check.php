<?php

// Dependency-free regression check for the three account screens reported on
// 31 October 2026. Run: php tests/Support/nextplay_account_compact_three_pages_check.php.
$root = dirname(__DIR__, 2);
$css = file_get_contents($root.'/resources/css/storefront-typography.css');
$theme = file_get_contents($root.'/resources/css/storefront-theme.css');
$published = file_get_contents($root.'/public/css/storefront-typography.css');
$layout = file_get_contents($root.'/resources/views/components/layouts/storefront.blade.php');
if ($css === false || $theme === false || $published === false || $layout === false) {
    throw new RuntimeException('Required typography source is missing');
}
$needles = [
    '.np-rewards-panel > h2',
    '.np-rewards-referral-banner h2',
    '.np-referral-how-card h3',
    '.np-referral-questions h3',
    '.np-rewards-progress-card__amount strong',
    '.np-rewards-referral-banner__icon',
    '.np-artwork-heading h1',
    '.np-artwork-list-card h3',
    '.np-artwork-list-card__action-row',
    '.np-artwork-list-card .np-artwork-button',
    'font: 700 var(--nps-h4)/1.4 var(--nps-font)',
    'font: 700 var(--nps-h5)/1.4 var(--nps-font)',
    'font:500 var(--nps-small)/1.4 var(--nps-font)',
];
foreach ($needles as $needle) {
    if (! str_contains($css, $needle)) {
        throw new RuntimeException('Missing compact account screen rule: '.$needle);
    }
}
foreach ([
    'resources/views/storefront/account/referrals.blade.php' => 'np-referral-share-grid',
    'resources/views/storefront/account/rewards.blade.php' => 'np-rewards-progress-card',
    'resources/views/storefront/account/artwork/index.blade.php' => 'x-storefront.account.artwork.list-card',
] as $file => $component) {
    $markup = file_get_contents($root.'/'.$file);
    if ($markup === false || ! str_contains($markup, $component)) {
        throw new RuntimeException('Account screen missing expected component: '.$file);
    }
}
$expected = "/* GENERATED by deploy/build-storefront-typography.py - do not edit. */\n".$theme."\n\n".$css."\n";
if ($expected !== $published) {
    throw new RuntimeException('Generated typography CSS is stale');
}
if (! str_contains($layout, '?v=20261031accountcompact4')) {
    throw new RuntimeException('Missing corrected CSS cache version');
}
if (str_contains($css, '.np-product-card {') || str_contains($css, '.np-filter-shell {')) {
    throw new RuntimeException('Scoped account CSS must not modify products or filters');
}
echo "PASS: Rewards, Refer a Friend and Artwork Approvals scoped typography checks.\n";
