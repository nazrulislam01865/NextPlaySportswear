#!/usr/bin/env python3
"""Build the static typography asset from the TWO centralized source files.

Existing public/build bundles may stay in place. Do not hand-edit the generated
public/css/storefront-typography.css file: run this script after making changes.
"""
from pathlib import Path
root = Path(__file__).resolve().parent.parent
sources = [root/'resources/css/storefront-theme.css', root/'resources/css/storefront-typography.css']
output = root/'public/css/storefront-typography.css'
output.parent.mkdir(parents=True, exist_ok=True)
header = '/* GENERATED by deploy/build-storefront-typography.py - do not edit. */\n'
output.write_text(header + '\n\n'.join(f.read_text() for f in sources) + '\n')
print(f'Built {output} ({output.stat().st_size:,} bytes)')
